// --- Helper to group job roles by category ---
export const rolesByCategory: Record<string, typeof JOB_ROLES> = {};
JOB_CATEGORIES.forEach((cat) => {
  rolesByCategory[cat.id] = JOB_ROLES.filter((r) => r.category === cat.id);
});

// --- Helper to get role label by ID ---
export const getRoleLabel = (roleId: string): string => {
  const role = JOB_ROLES.find((r) => r.id === roleId);
  return role ? role.label : roleId;
};
